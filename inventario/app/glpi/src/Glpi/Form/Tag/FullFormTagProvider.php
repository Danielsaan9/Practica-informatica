<?php

namespace Glpi\Form\Tag;

use Glpi\Form\AnswersSet;
use Glpi\Form\Destination\CommonITILField\ContentField;
use Glpi\Form\Form;
use Override;

final class FullFormTagProvider implements TagProviderInterface, TagWithIdValueInterface
{
    #[Override]
    public function getTagColor(): string
    {
        return "purple";
    }

    #[Override]
    public function getTags(Form $form): array
    {
        return [$this->getTagForForm($form)];
    }

    #[Override]
    public function getTagContentForValue(
        string $value,
        AnswersSet $answers_set
    ): string {
        $form = Form::getById((int) $value);
        if ($form === false) {
            return '';
        }

        $content = (new ContentField())
            ->getAutoGeneratedConfig($form, $answers_set)
            ->getValue()
        ;

        // getAutoGeneratedConfig() emits unresolved question/answer tags, resolve them here.
        return (new FormTagsManager())->insertTagsContent($content, $answers_set);
    }

    #[Override]
    public function getItemtype(): string
    {
        return Form::class;
    }

    #[Override]
    public function getTagFromRawValue(string $value): ?Tag
    {
        $form = Form::getById((int) $value);
        if (!$form) {
            return null;
        }

        return $this->getTagForForm($form);
    }

    public function getTagForForm(Form $form): Tag
    {
        return new Tag(
            label: __('Full form (all questions and answers)'),
            value: $form->getId(),
            provider: $this,
        );
    }
}
